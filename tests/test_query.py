class TestWatermarkQueryFilters(unittest.TestCase):
    """Tests for SQL filter expressions generated by WatermarkQuery methods."""

    def setUp(self):
        self.spark = MockSparkSession()
        self.query = WatermarkQuery(self.spark)

    def test_init_state(self):
        """Edge case: initial query state has no filters and sort disabled."""
        self.assertEqual(self.query._filters, [])
        self.assertFalse(self.query._sort)
        self.assertFalse(self.query._single)

    def test_source_single(self):
        """Single source filter."""
        self.query.source("ORACLE")
        self.assertEqual(self.query._filters, [f"{c.COL_SOURCE} IN ('ORACLE')"])

    def test_source_multiple(self):
        """Multiple sources in a single call (OR-ed)."""
        self.query.source("ORACLE", "SAP", "SAGE")
        self.assertEqual(self.query._filters, [f"{c.COL_SOURCE} IN ('ORACLE', 'SAP', 'SAGE')"])

    def test_source_chained(self):
        """Edge case: multiple calls to source() chain separate filters."""
        self.query.source("ORACLE").source("SAP")
        self.assertEqual(
            self.query._filters,
            [f"{c.COL_SOURCE} IN ('ORACLE')", f"{c.COL_SOURCE} IN ('SAP')"]
        )

    def test_area_single_and_multiple(self):
        """Single and multiple area filters."""
        self.query.area("COMPRES")
        self.assertEqual(self.query._filters, [f"{c.COL_AREA} IN ('COMPRES')"])

        q2 = WatermarkQuery(self.spark).area("COMPRES", "VENDES", "FINANCES")
        self.assertEqual(q2._filters, [f"{c.COL_AREA} IN ('COMPRES', 'VENDES', 'FINANCES')"])

    def test_table_single_and_multiple(self):
        """Single and multiple table name filters."""
        self.query.table("PORDER")
        self.assertEqual(self.query._filters, [f"{c.COL_TABLE_NAME} IN ('PORDER')"])

        q2 = WatermarkQuery(self.spark).table("BKPF", "BSEG", "KNA1")
        self.assertEqual(q2._filters, [f"{c.COL_TABLE_NAME} IN ('BKPF', 'BSEG', 'KNA1')"])

    def test_dimension_default_true(self):
        """Default dimension() call should filter for true."""
        self.query.dimension()
        self.assertEqual(self.query._filters, [f"{c.COL_IS_DIMENSION} = true"])

    def test_dimension_explicit_true_and_false(self):
        """Explicit boolean values for dimension()."""
        q_true = WatermarkQuery(self.spark).dimension(True)
        self.assertEqual(q_true._filters, [f"{c.COL_IS_DIMENSION} = true"])

        q_false = WatermarkQuery(self.spark).dimension(False)
        self.assertEqual(q_false._filters, [f"{c.COL_IS_DIMENSION} = false"])

    def test_active_only(self):
        """active_only() adds ACTIVE = true."""
        self.query.active_only()
        self.assertEqual(self.query._filters, [f"{c.COL_ACTIVE} = true"])

    def test_runnable(self):
        """
        runnable() automatically adds ACTIVE = true AND
        COALESCE(NEXT_RUN_MODE, CASE WHEN WATERMARK IS NULL THEN 'FULL_RELOAD' ELSE LOAD_MODE END) != 'SKIP'
        """
        self.query.runnable()
        self.assertEqual(len(self.query._filters), 2)
        self.assertEqual(self.query._filters[0], f"{c.COL_ACTIVE} = true")
        self.assertIn("!= 'SKIP'", self.query._filters[1])
        self.assertIn(c.COL_NEXT_RUN_MODE, self.query._filters[1])
        self.assertIn(c.COL_WATERMARK_LAST, self.query._filters[1])
        self.assertIn(c.COL_LOAD_MODE, self.query._filters[1])

    def test_mode_single_and_multiple(self):
        """Filter by permanent load mode."""
        self.query.mode("INCREMENTAL")
        self.assertEqual(self.query._filters, [f"{c.COL_LOAD_MODE} IN ('INCREMENTAL')"])

        q2 = WatermarkQuery(self.spark).mode("INCREMENTAL", "FULL_RELOAD")
        self.assertEqual(q2._filters, [f"{c.COL_LOAD_MODE} IN ('INCREMENTAL', 'FULL_RELOAD')"])

    def test_ordered(self):
        """ordered() enables sorting flag and returns self."""
        res = self.query.ordered()
        self.assertTrue(self.query._sort)
        self.assertIs(res, self.query)


class TestWatermarkQueryWhereMethod(unittest.TestCase):
    """Detailed tests for the generic .where(**kwargs) filter method."""

    def setUp(self):
        self.spark = MockSparkSession()
        self.query = WatermarkQuery(self.spark)

    def test_where_string(self):
        """String value escaping and column resolution."""
        self.query.where(silver_table="silver.compres_porder")
        self.assertEqual(self.query._filters, [f"{c.COL_SILVER_TABLE} = 'silver.compres_porder'"])

    def test_where_single_quote_escaping(self):
        """Edge case: string containing single quotes must be properly escaped."""
        self.query.where(table="O'Connor_Table")
        self.assertEqual(self.query._filters, [f"{c.COL_TABLE_NAME} = 'O''Connor_Table'"])

    def test_where_empty_string(self):
        """Edge case: empty string."""
        self.query.where(area="")
        self.assertEqual(self.query._filters, [f"{c.COL_AREA} = ''"])

    def test_where_none_is_null(self):
        """Edge case: None maps to IS NULL."""
        self.query.where(next_run_mode=None)
        self.assertEqual(self.query._filters, [f"{c.COL_NEXT_RUN_MODE} IS NULL"])

    def test_where_boolean(self):
        """Booleans map to 'true' or 'false' literals."""
        self.query.where(active=True, is_dimension=False)
        self.assertIn(f"{c.COL_ACTIVE} = true", self.query._filters)
        self.assertIn(f"{c.COL_IS_DIMENSION} = false", self.query._filters)

    def test_where_numeric_int_and_float(self):
        """Numeric values rendered without quotes."""
        self.query.where(run_order=2, window_days=0)
        self.assertIn(f"{c.COL_RUN_ORDER} = 2", self.query._filters)
        self.assertIn(f"{c.COL_WINDOW_DAYS} = 0", self.query._filters)

    def test_where_custom_column(self):
        """Edge case: unmapped custom column gets uppercased."""
        self.query.where(custom_flag="SPECIAL")
        self.assertEqual(self.query._filters, ["CUSTOM_FLAG = 'SPECIAL'"])


class TestWatermarkQueryExecution(unittest.TestCase):
    """Tests for terminal methods .build() and .one() including edge cases."""

    def test_build_empty_result(self):
        """Edge case: .build() on 0 matching rows returns empty list without error."""
        spark = MockSparkSession(MockDataFrame(rows=[]))
        res = WatermarkQuery(spark).source("NON_EXISTENT").build()
        self.assertEqual(res, [])
        self.assertIsInstance(res, list)

    def test_build_multiple_results(self):
        """Normal case: .build() returns a list of WatermarkConfig objects."""
        rows = [
            sample_row_dict(TABLE_NAME="T1", RUN_ORDER=1),
            sample_row_dict(TABLE_NAME="T2", RUN_ORDER=2),
            sample_row_dict(TABLE_NAME="T3", RUN_ORDER=3),
        ]
        spark = MockSparkSession(MockDataFrame(rows=rows))
        configs = WatermarkQuery(spark).source("ORACLE").ordered().build()

        self.assertEqual(len(configs), 3)
        self.assertTrue(all(isinstance(c, WatermarkConfig) for c in configs))
        self.assertEqual([c.table_name for c in configs], ["T1", "T2", "T3"])

    def test_build_passes_filters_and_ordering_to_spark(self):
        """Verify that SQL filter string and sort columns are passed to DataFrame."""
        mock_df = MockDataFrame(rows=[sample_row_dict()])
        spark = MockSparkSession(mock_df)

        WatermarkQuery(spark).source("SAP").area("COMPRES").ordered().build()

        spark.read.table.assert_called_once_with(c.TABLE_NAME)
        self.assertEqual(mock_df.filter_arg, f"{c.COL_SOURCE} IN ('SAP') AND {c.COL_AREA} IN ('COMPRES')")
        self.assertEqual(mock_df.order_by_args, (c.COL_SOURCE, c.COL_RUN_ORDER, c.COL_TABLE_NAME))

    def test_build_without_sort_does_not_call_order_by(self):
        """When .ordered() is not called, orderBy() is not executed on DataFrame."""
        mock_df = MockDataFrame(rows=[sample_row_dict()])
        spark = MockSparkSession(mock_df)

        WatermarkQuery(spark).source("SAP").build()
        self.assertIsNone(mock_df.order_by_args)

    def test_one_exact_match(self):
        """Normal case: .one() returns single WatermarkConfig directly."""
        row = sample_row_dict(TABLE_NAME="PORDER")
        spark = MockSparkSession(MockDataFrame(rows=[row]))

        cfg = WatermarkQuery(spark).source("ORACLE").table("PORDER").one()
        self.assertIsInstance(cfg, WatermarkConfig)
        self.assertEqual(cfg.table_name, "PORDER")
        self.assertEqual(cfg.source, "ORACLE")

    def test_one_zero_rows_raises_value_error(self):
        """Edge case: .one() with 0 rows raises ValueError with informative message."""
        spark = MockSparkSession(MockDataFrame(rows=[]))
        query = WatermarkQuery(spark).source("ORACLE").table("MISSING_TABLE")

        with self.assertRaises(ValueError) as ctx:
            query.one()

        err_msg = str(ctx.exception)
        self.assertIn(f"No row found in {c.TABLE_NAME}", err_msg)
        self.assertIn("TABLE_NAME IN ('MISSING_TABLE')", err_msg)

    def test_one_multiple_rows_raises_value_error(self):
        """Edge case: .one() with >1 rows raises ValueError indicating ambiguous match."""
        rows = [
            sample_row_dict(TABLE_NAME="PORDER", SOURCE="ORACLE"),
            sample_row_dict(TABLE_NAME="PORDER", SOURCE="SAP"),
        ]
        spark = MockSparkSession(MockDataFrame(rows=rows))
        query = WatermarkQuery(spark).table("PORDER")

        with self.assertRaises(ValueError) as ctx:
            query.one()

        err_msg = str(ctx.exception)
        self.assertIn("Expected exactly 1 row but got 2", err_msg)
        self.assertIn("Add .source() or .table() to narrow down", err_msg)

    def test_method_chaining_fluent_api(self):
        """Verify that every filter method returns the query instance for fluent chaining."""
        spark = MockSparkSession()
        q = WatermarkQuery(spark)

        self.assertIs(q.source("ORACLE"), q)
        self.assertIs(q.area("COMPRES"), q)
        self.assertIs(q.table("PORDER"), q)
        self.assertIs(q.dimension(True), q)
        self.assertIs(q.active_only(), q)
        self.assertIs(q.runnable(), q)
        self.assertIs(q.mode("INCREMENTAL"), q)
        self.assertIs(q.where(window_days=3), q)
        self.assertIs(q.ordered(), q)

        # All 9 steps should be registered in _filters
        self.assertEqual(len(q._filters), 9)


class TestWatermarkConfigEdgeCasesFromQuery(unittest.TestCase):
    """Verifies that configs returned by WatermarkQuery correctly expose edge-case properties."""

    def test_null_watermark_is_first_run(self):
        """Edge case: new table with WATERMARK_LAST_VALUE = None is considered first run."""
        row = sample_row_dict(WATERMARK_LAST_VALUE=None, LOAD_MODE=c.MODE_INCREMENTAL, NEXT_RUN_MODE=None)
        spark = MockSparkSession(MockDataFrame(rows=[row]))

        cfg = WatermarkQuery(spark).source("ORACLE").table("NEW_TABLE").one()
        self.assertTrue(cfg.is_first_run)
        self.assertIsNone(cfg.watermark_last)
        self.assertIsNone(cfg.from_date)
        # Should fallback to FULL_RELOAD because watermark is null
        self.assertEqual(cfg.effective_mode, c.MODE_FULL_RELOAD)

    def test_override_takes_precedence_over_load_mode(self):
        """Edge case: NEXT_RUN_MODE overrides permanent LOAD_MODE."""
        row = sample_row_dict(
            LOAD_MODE=c.MODE_INCREMENTAL,
            NEXT_RUN_MODE=c.MODE_FULL_RELOAD,
            WATERMARK_LAST_VALUE=datetime(2026, 1, 1)
        )
        spark = MockSparkSession(MockDataFrame(rows=[row]))
        cfg = WatermarkQuery(spark).one()

        self.assertEqual(cfg.load_mode, c.MODE_INCREMENTAL)
        self.assertEqual(cfg.next_run_mode, c.MODE_FULL_RELOAD)
        self.assertEqual(cfg.effective_mode, c.MODE_FULL_RELOAD)

    def test_skip_mode_sets_should_run_false(self):
        """Edge case: effective_mode = SKIP sets should_run = False."""
        row = sample_row_dict(NEXT_RUN_MODE=c.MODE_SKIP)
        spark = MockSparkSession(MockDataFrame(rows=[row]))
        cfg = WatermarkQuery(spark).one()

        self.assertEqual(cfg.effective_mode, c.MODE_SKIP)
        self.assertFalse(cfg.should_run)

    def test_pk_columns_variations(self):
        """Edge case: pk_columns JSON array parsing and empty list fallback."""
        # Standard array
        row1 = sample_row_dict(PK_COLUMNS='["COL1", "COL2"]')
        cfg1 = WatermarkConfig(row1)
        self.assertEqual(cfg1.pk_columns, ["COL1", "COL2"])

        # None / null in control table
        row2 = sample_row_dict(PK_COLUMNS=None)
        cfg2 = WatermarkConfig(row2)
        self.assertEqual(cfg2.pk_columns, [])

        # Empty string
        row3 = sample_row_dict(PK_COLUMNS="")
        cfg3 = WatermarkConfig(row3)
        self.assertEqual(cfg3.pk_columns, [])

    def test_dynamic_extra_field_access(self):
        """Edge case: arbitrary custom columns in the row are accessible on WatermarkConfig."""
        row = sample_row_dict(CUSTOM_TAG="HIGH_PRIORITY", RETRY_COUNT=3)
        spark = MockSparkSession(MockDataFrame(rows=[row]))
        cfg = WatermarkQuery(spark).one()

        self.assertEqual(cfg.get("CUSTOM_TAG"), "HIGH_PRIORITY")
        self.assertEqual(cfg.get("custom_tag"), "HIGH_PRIORITY")
        self.assertEqual(cfg.get("RETRY_COUNT"), 3)
        self.assertEqual(cfg.custom_tag, "HIGH_PRIORITY")
        self.assertEqual(cfg.retry_count, 3)


