class MockDataFrame:
    """Mock Spark DataFrame that records calls and simulates filtering/ordering."""
    def __init__(self, rows=None):
        self.rows = rows if rows is not None else []
        self.filter_arg = None
        self.order_by_args = None

    def filter(self, condition):
        self.filter_arg = condition
        return self

    def orderBy(self, *columns):
        self.order_by_args = columns
        return self

    def collect(self):
        return self.rows


class MockSparkSession:
    """Mock SparkSession with .read.table support."""
    def __init__(self, mock_df=None):
        self.mock_df = mock_df or MockDataFrame()
        self.read = MagicMock()
        self.read.table.return_value = self.mock_df


